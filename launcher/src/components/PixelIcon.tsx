export type IconName = keyof typeof ICONS;

interface Rect {
  x: number;
  y: number;
  w: number;
}

const RUNS: Record<IconName, { w: number; h: number; rects: Rect[] }> = Object.fromEntries(
  Object.entries(ICONS).map(([name, grid]) => {
    const rects: Rect[] = [];
    grid.forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        if (row[x] === '#') {
          let end = x;
          while (end < row.length && row[end] === '#') end++;
          rects.push({ x, y, w: end - x });
          x = end;
        } else x++;
      }
    });
    return [name, { w: grid[0].length, h: grid.length, rects }];
  }),
) as Record<IconName, { w: number; h: number; rects: Rect[] }>;

interface Props {
  name: IconName;
  size?: number;
  className?: string;
}

export const PixelIcon = memo(function PixelIcon({ name, size = 16, className }: Props) {
  const { w, h, rects } = RUNS[name];
  return (
    <svg
      width={size}
      height={Math.round((size * h) / w)}
      viewBox={`0 0 ${w} ${h}`}
      shapeRendering="crispEdges"
      fill="currentColor"
      className={className}
      aria-hidden
    >
      {rects.map((r, i) => (
        <rect key={i} x={r.x} y={r.y} width={r.w} height={1} />
      ))}
    </svg>
  );
});
