    /** A fresh grid for the named preset, or null when the name is unknown. */
    public static int[][] byName(String name) {
        for (int i = 0; i < NAMES.length; i++) {
            if (NAMES[i].equals(name)) return decode(MASKS[i]);
        }
        return null;
    }

    public static int[][] defaultGrid() {
        return decode(MASKS[0]);
    }

    private static int[][] decode(String[] mask) {
        int[][] grid = new int[SIZE][SIZE];
        for (int y = 0; y < SIZE; y++) {
            String row = mask[y];
            for (int x = 0; x < SIZE && x < row.length(); x++) {
                grid[y][x] = row.charAt(x) == '#' ? WHITE : 0;
            }
        }
        return grid;
    }
